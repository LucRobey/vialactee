    def live_asserved_novelty(self) -> float: ...
    @property
    def live_combined_novelty(self) -> float: ...
    @property
    def novelty_lm(self) -> float: ...
    @property
    def novelty_gm(self) -> float: ...
    @property
    def salience_gradient(self) -> float: ...
    @property
    def power_gradient(self) -> float: ...


