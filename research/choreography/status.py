"""Status of the choreography lab: where every lab mode stands, and what waits for the owner.

Reads the three committed records (gates.json, queue.json, verdicts.jsonl) and the list of lab modes in
candidates/, and writes STATUS.md. Generated: do not edit STATUS.md by hand, run this again instead.

    python -m research.choreography.status

Any Python environment of the project can run it: it draws nothing.
"""
from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Dict, List

from research.choreography import records

STATUS = Path(__file__).resolve().parent / "STATUS.md"


def _gate_cells(name: str, gates: Dict[str, dict], candidates: Path, production: Path) -> tuple:
    """(latest gate, failed rule) as the table shows them."""
    record = gates.get(name)
    if record is None:
        return "never checked", "-"
    result = f"passed {record.get('date')}" if record.get("passed") else f"FAILED {record.get('date')}"
    now = records.source_sha(records.mode_file(name, candidates, production))
    if record.get("source_sha") and now and record["source_sha"] != now:
        result += " (the mode has changed since: check it again)"
    failed = ", ".join(f"{n} ({records.RULE_NAMES.get(n, '?')})" for n in record.get("failed_rules", [])) or "-"
    return result, failed


def _mode_row(name: str, gates: Dict[str, dict], queue: List[dict], verdicts: List[dict], candidates: Path, production: Path) -> str:
    gate, failed = _gate_cells(name, gates, candidates, production)
    mine = [e for e in queue if name in (e.get("mode"), e.get("against"))]
    still = records.waiting(mine, verdicts)
    chosen = not_chosen = no_difference = 0
    feeds: Counter = Counter()
    for v in verdicts:
        if v.get("kind") == "modes":
            if name not in (v.get("mode"), v.get("against")):
                continue
            if v.get("choice") == "none":
                no_difference += 1
            elif v.get("chosen_mode") == name:
                chosen += 1
            else:
                not_chosen += 1
        elif records.verdict_mode(v) == name:                 # a feeds clip: the owner chose a way of hearing, not a mode
            feeds["no difference" if v.get("choice") == "none" else str(v.get("chosen_feed"))] += 1
    against = f"{chosen} / {not_chosen} / {no_difference}" if chosen + not_chosen + no_difference else "-"
    heard = ", ".join(f"{k} {n}" for k, n in sorted(feeds.items())) or "-"
    return f"| `{name}` | {gate} | {failed} | {len(mine)} | {len(still)} | {against} | {heard} |"


def _what(entry: dict) -> str:
    if entry.get("against"):
        return f"`{entry['mode']}` against `{entry['against']}`, both hearing: {entry.get('feed')}"
    return f"`{entry['mode']}`, its feeds side by side"


def build(gates: Dict[str, dict], queue: List[dict], verdicts: List[dict], candidate_names: List[str],
          candidates: Path = records.CANDIDATES, production: Path = records.PRODUCTION_MODES) -> str:
    """The text of STATUS.md."""
    lines = ["# Choreography lab: status", "",
             "Generated by `python -m research.choreography.status` from `gates.json`, `queue.json` and `verdicts.jsonl`.",
             "Do not edit by hand. The gate's limits are provisional proposals, not decisions of the owner.", "",
             "## Lab modes", "",
             "| Mode | Latest gate | Failed rule | Clips nominated | Still waiting | Against another mode: chosen / not chosen / no difference | Feeds clips: what the owner chose |",
             "|---|---|---|---|---|---|---|"]
    lines += [_mode_row(n, gates, queue, verdicts, candidates, production) for n in candidate_names] or ["| (no lab mode yet) | | | | | | |"]
    others = sorted(set(gates) - set(candidate_names))
    if others:
        lines += ["", "## Other modes that went through the gate", "", "| Mode | Latest gate | Failed rule |", "|---|---|---|"]
        lines += ["| `{}` | {} | {} |".format(n, *_gate_cells(n, gates, candidates, production)) for n in others]
    still = records.waiting(queue, verdicts)
    lines += ["", f"## Waiting for the owner: {len(still)}", ""]
    if still:
        lines += ["| Clip | What is compared | Track | From | Nominated | Note |", "|---|---|---|---|---|---|"]
        for e in still:
            m = int(e["start_s"] // 60)
            lines.append(f"| `{e['clip']}` | {_what(e)} | {e['track']} | {m}:{int(e['start_s'] - 60 * m):02d}, {e['duration_s']:.0f} s "
                         f"| {e['nominated']} | {str(e.get('note') or '').replace('|', '/')} |")
        lines += ["", "To judge them: start the clip page (`python -m research.choreography.clip_server`); they are listed first.",
                  "If a clip is missing on this computer: `python -m research.choreography.nominate --rebuild`."]
    else:
        lines.append("Nothing is waiting.")
    return "\n".join(lines) + "\n"


def write(path: Path = STATUS) -> Path:
    path.write_text(build(records.read_gates(), records.read_queue(), records.read_verdicts(), records.candidate_names()), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(f"wrote {write()}")
