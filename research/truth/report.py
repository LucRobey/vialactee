"""Summary of the automatic truth draft: what exists per track and what most needs a human ear."""
from __future__ import annotations

import json
from pathlib import Path
from typing import List


def _total(regs: List[dict]) -> float:
    return sum(r["end"] - r["start"] for r in regs)


def _pct(x: float, whole: float) -> str:
    return f"{100.0 * x / whole:.0f}%" if whole > 0 else "-"


def _mmss(t: float) -> str:
    return f"{int(t // 60)}:{t % 60:04.1f}"


def write_report(tracks_dir: Path, out_path: Path) -> None:
    rows, todo = [], []
    for path in sorted(tracks_dir.glob("*.json")):
        d = json.loads(path.read_text(encoding="utf-8"))
        tr, r, beats = d["track"], d["regions"], d["beats"]
        dur = tr["duration"]
        live = [b for b in beats if not b["no_beat"] and b["main"]]
        halves = sum(1 for b in beats if not b["main"])
        m2 = sum(1 for b in live if b["level"] == "M2")
        bar_ok = sum(1 for b in live if b["bar_pos_level"] == "M2")
        bpms = sorted(b["bpm"] for b in live if b["bpm"] > 0)
        bpm = bpms[len(bpms) // 2] if bpms else 0.0
        human = sum(1 for x in r["no_beat"] if x["level"] in ("H", "A"))
        kick_m2 = _total([k for k in r["kick_present"] if k["level"] == "M2"])
        name = tr["file"].rsplit(".", 1)[0][:34]
        pieces = d.get("drums", {}).get("pieces", {})
        kicks = pieces.get("kick", [])
        kick_ok = _pct(sum(1 for h in kicks if h[2] == "M2"), len(kicks)) if kicks else "-"
        counts = " / ".join(str(sum(1 for h in pieces.get(k, []) if h[2] != "W")) for k in ("kick", "snare", "hat")) if pieces else "-"
        rows.append(
            f"| {tr['id']} | {name} | {tr['group']} | {bpm:.0f} | {_pct(halves, len(beats))} | {_pct(m2, len(live))} | "
            f"{d['meter']['beats_per_bar']}{' (!)' if d['meter']['conflict'] else ''} | {_pct(bar_ok, len(live))} | "
            f"{len(r['no_beat'])} ({human}) | {_pct(_total(r['kick_present']), dur)} | {_pct(kick_m2, dur)} | "
            f"{len(r['breakdown'])} | {len(r['riser'])} | {_pct(_total(r['bass_present']), dur)} | "
            f"{_pct(_total(r['vocal_present']), dur)} | {counts} | {kick_ok} |"
        )
        items = []
        if d["meter"]["conflict"]:
            items.append(f"the two trackers count bars differently ({d['meter']['beat_this_says']} and "
                         f"{d['meter']['beatnet_says']} beats per bar)")
        if halves / max(1, len(beats)) > 0.2:
            items.append(f"{_pct(halves, len(beats))} of the grid is half-beats: check that the tempo shown ({bpm:.0f}) is the one you would tap")
        if live and bar_ok / len(live) < 0.6:
            items.append(f"the \"1\" of the bar is agreed on only {_pct(bar_ok, len(live))} of the beats")
        if live and m2 / len(live) < 0.8:
            items.append(f"only {_pct(m2, len(live))} of the beats are confirmed by two trackers")
        if kicks and sum(1 for h in kicks if h[2] == "M2") / len(kicks) < 0.6:
            items.append(f"only {kick_ok} of the drum model's kicks match a measured low thump: the kicks here need your ear")
        machine_nb = [x for x in r["no_beat"] if x["level"] == "M1"]
        if machine_nb:
            items.append("no-beat stretches to confirm: " + ", ".join(f"{_mmss(x['start'])} to {_mmss(x['end'])}" for x in machine_nb))
        if r["breakdown"]:
            items.append("kick leaves and returns: " + ", ".join(f"{_mmss(x['start'])} to {_mmss(x['end'])}" for x in r["breakdown"]))
        if items:
            todo.append(f"**{tr['id']} {name}**\n" + "\n".join(f"- {i}" for i in items))

    lines = [
        "# Automatic truth draft: report",
        "",
        "Generated by `build_truth.py`. Everything here is machine-made unless counted in brackets as the owner's.",
        "",
        "| # | Track | Group | BPM | Half-beats in the grid | Beats confirmed by 2 trackers | Beats per bar | \"1\" agreed | No-beat stretches (owner's) | "
        "Kick present | of which 2 methods agree | Breakdowns | Risers | Bass present | Voice present | "
        "Kick / snare / hat hits | Kicks confirmed by measurement |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        "(!) = the two trackers disagree on the number of beats per bar.",
        "",
        "## What most needs a human ear",
        "",
        "\n\n".join(todo) if todo else "Nothing flagged.",
        "",
    ]
    out_path.write_text("\n".join(lines), encoding="utf-8")
